      // Pure-hex runs are almost always hashes (git SHAs, MD5/SHA digests),
      // which are public by nature and appear constantly in logs and diffs.
      if (/^[0-9a-f]+$/i.test(value)) return false;
      const classes = [/[a-z]/, /[A-Z]/, /[0-9]/].filter((c) => c.test(value)).length;
